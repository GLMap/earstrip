#!/bin/bash
# Builds the module twice with Emscripten (EMSDK=<emsdk dir>): dist/earstrip.wasm with WebAssembly SIMD, where the
# ear test takes two blockers at a time (Chrome 91, Firefox 89, Safari 16.4, Node 16.4 and later), and
# dist/earstrip-scalar.wasm without it for older engines; dist/wasm.js and dist/wasm-scalar.js inline them as base64.
set -e
cd "$(dirname "$0")"
[ -n "$EMSDK" ] && source "$EMSDK/emsdk_env.sh" >/dev/null 2>&1
mkdir -p dist
build() {
  em++ -O3 -std=c++17 $2 -I../include -DEARSTRIP_SMALL_CONSTRAINED -DNDEBUG -fno-exceptions -fno-rtti -flto \
    -sSTANDALONE_WASM --no-entry -sALLOW_MEMORY_GROWTH -sINITIAL_MEMORY=4MB -sMAXIMUM_MEMORY=4GB -sSTACK_SIZE=256KB \
    -sMALLOC=emmalloc -sFILESYSTEM=0 \
    src/wasm.cpp -o dist/$1.wasm
}
build earstrip -msimd128
build earstrip-scalar
node -e "
const fs = require('fs');
for (const [wasm, js] of [['earstrip', 'wasm'], ['earstrip-scalar', 'wasm-scalar']]) {
  const b = fs.readFileSync('dist/' + wasm + '.wasm');
  fs.writeFileSync('dist/' + js + '.js', '// Generated by build.sh from src/wasm.cpp.\nexport default \'' + b.toString('base64') + '\';\n');
  console.log(wasm + '.wasm', b.length, 'bytes');
}
"
