#!/bin/bash
# Builds dist/earstrip.wasm and dist/wasm.js (the module inlined as base64) with Emscripten (EMSDK=<emsdk dir>).
set -e
cd "$(dirname "$0")"
[ -n "$EMSDK" ] && source "$EMSDK/emsdk_env.sh" >/dev/null 2>&1
mkdir -p dist
em++ -O3 -std=c++17 -I../include -DEARSTRIP_SMALL_CONSTRAINED -DNDEBUG -fno-exceptions -fno-rtti -flto \
  -sSTANDALONE_WASM --no-entry -sALLOW_MEMORY_GROWTH -sINITIAL_MEMORY=4MB -sMAXIMUM_MEMORY=4GB -sSTACK_SIZE=256KB \
  -sMALLOC=emmalloc -sFILESYSTEM=0 \
  src/wasm.cpp -o dist/earstrip.wasm
node -e "
const fs = require('fs');
const b = fs.readFileSync('dist/earstrip.wasm');
fs.writeFileSync('dist/wasm.js', '// Generated by build.sh from src/wasm.cpp.\nexport default \'' + b.toString('base64') + '\';\n');
console.log('earstrip.wasm', b.length, 'bytes');
"
